// Renders the halftone assets used across the site from the photos in assets/photos.
//
//   public/photos/<name>.jpg      re-encoded original (no EXIF / GPS)
//   public/halftone/<name>.png    alpha mask of dots, colourised in CSS with mask-image
//   lib/portrait-dots.ts          luminance grid for the interactive canvas portrait
//
// Run with `pnpm halftone` whenever a photo changes.
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "assets/photos");
const OUT_PHOTOS = path.join(ROOT, "public/photos");
const OUT_HALFTONE = path.join(ROOT, "public/halftone");

const WIDTH = 1200;
const CELL = 9;

async function luminanceGrid(file, cols) {
  const meta = await sharp(file).metadata();
  const rows = Math.round((cols * meta.height) / meta.width);
  const { data } = await sharp(file)
    .resize(cols, rows, { fit: "fill" })
    .grayscale()
    .normalise()
    .raw()
    .toBuffer({ resolveWithObject: true });
  return { cols, rows, data: Array.from(data) };
}

function dotsSvg({ cols, rows, data }, cell) {
  const w = cols * cell;
  const h = rows * cell;
  let circles = "";
  for (let y = 0; y < rows; y++) {
    const offset = y % 2 ? cell / 2 : 0;
    for (let x = 0; x < cols; x++) {
      const lum = data[y * cols + x] / 255;
      const r = (1 - lum) ** 1.15 * cell * 0.62;
      if (r < 0.45) continue;
      const cx = (x * cell + cell / 2 + offset).toFixed(1);
      const cy = (y * cell + cell / 2).toFixed(1);
      circles += `<circle cx="${cx}" cy="${cy}" r="${r.toFixed(2)}"/>`;
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"><g fill="#000">${circles}</g></svg>`;
}

await mkdir(OUT_PHOTOS, { recursive: true });
await mkdir(OUT_HALFTONE, { recursive: true });

const files = (await readdir(SRC)).filter((f) => f.endsWith(".jpg"));
for (const name of files) {
  const file = path.join(SRC, name);
  const base = name.replace(/\.jpg$/, "");

  await sharp(file)
    .resize({ width: 1600, withoutEnlargement: true })
    .jpeg({ quality: 82, mozjpeg: true })
    .toFile(path.join(OUT_PHOTOS, name));

  const grid = await luminanceGrid(file, Math.round(WIDTH / CELL));
  await sharp(Buffer.from(dotsSvg(grid, CELL)))
    .webp({ quality: 60, alphaQuality: 55, effort: 6 })
    .toFile(path.join(OUT_HALFTONE, `${base}.webp`));

  console.log(`halftone: ${base}`);
}

const portrait = await luminanceGrid(path.join(SRC, "walter-morales.jpg"), 64);
await writeFile(
  path.join(ROOT, "lib/portrait-dots.ts"),
  `// Generated by scripts/halftone.mjs. Do not edit by hand.\nexport const portraitDots: { cols: number; rows: number; data: number[] } = ${JSON.stringify(
    {
      cols: portrait.cols,
      rows: portrait.rows,
      data: portrait.data.map((v) => Math.round((v / 255) * 99)),
    },
  )};\n`,
);
console.log("portrait grid written");
